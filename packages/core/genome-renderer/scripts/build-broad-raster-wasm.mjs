#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../../..');
execFileSync(
  'cargo',
  ['build', '--release', '-p', 'broad-raster', '--target', 'wasm32-unknown-unknown'],
  { cwd: root, stdio: 'inherit' }
);
const bytes = readFileSync(join(root, 'target/wasm32-unknown-unknown/release/broad_raster.wasm'));
const out = join(
  root,
  'packages/core/genome-renderer/src/broad-raster/broad-raster-wasm-bytes.generated.ts'
);
writeFileSync(
  out,
  `// Generated by packages/core/genome-renderer/scripts/build-broad-raster-wasm.mjs
// from tools/broad-raster. Do not edit.
export const BROAD_RASTER_WASM_SHA256 =
  '${createHash('sha256').update(bytes).digest('hex')}';
export const BROAD_RASTER_WASM_BASE64 =
  '${bytes.toString('base64')}';
`
);
console.log(`wrote ${out} (${bytes.length} bytes)`);
