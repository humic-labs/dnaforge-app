#!/usr/bin/env node
import { readFile, writeFile, mkdir, readdir, access } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WORKSPACE_ROOT = resolve(HERE, '../resources/sample-workspaces/standard-samples');
const WORKSPACE_DIR = join(WORKSPACE_ROOT, 'workspace');
const MANIFEST_PATH = join(WORKSPACE_ROOT, 'sourcing-manifest.json');
const PROVENANCE_JSON = join(WORKSPACE_DIR, 'PROVENANCE.json');
const REPO_ROOT = resolve(HERE, '../../..');
const FIXTURE_PROVENANCE_MD = join(REPO_ROOT, 'test-fixtures/PROVENANCE.md');
const MD_BEGIN =
  '<!-- AUTO:example-workspace BEGIN — regenerated by apps/desktop/scripts/build-example-workspace.mjs; do not edit by hand -->';
const MD_END = '<!-- AUTO:example-workspace END -->';

const NCBI_TOOL = 'dnaforge-example-builder';
const NCBI_EMAIL = 'hello@dnaforge.com';
const NCBI_MIN_INTERVAL_MS = 350;

const args = process.argv.slice(2);
const FORCE = args.includes('--force');
const ONLY = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;

let lastNcbiAt = 0;
async function ncbiThrottle() {
  const wait = lastNcbiAt + NCBI_MIN_INTERVAL_MS - Date.now();
  if (wait > 0) await new Promise((r) => setTimeout(r, wait));
  lastNcbiAt = Date.now();
}

async function httpText(url, { throttle } = {}) {
  if (throttle) await ncbiThrottle();
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': `${NCBI_TOOL} (${NCBI_EMAIL})` } });
      if (res.ok) return await res.text();
      if (res.status === 429 || res.status >= 500) {
        await new Promise((r) => setTimeout(r, 700 * attempt));
        continue;
      }
      throw new Error(`HTTP ${res.status} for ${url}`);
    } catch (err) {
      if (attempt === 4) throw err;
      await new Promise((r) => setTimeout(r, 700 * attempt));
    }
  }
  throw new Error('unreachable');
}

async function httpJson(url) {
  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  const res = await fetch(url, {
    headers: {
      'User-Agent': NCBI_TOOL,
      Accept: 'application/vnd.github+json',
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
    },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

function assertGenBank(text, id) {
  if (!/^LOCUS\s/m.test(text)) throw new Error(`Non-GenBank content for ${id}`);
  return text;
}

function stripSourceFeature(text) {
  const lines = text.split('\n');
  const out = [];
  let inFeatures = false;
  let skipping = false;
  for (const line of lines) {
    if (line.startsWith('FEATURES')) {
      inFeatures = true;
      skipping = false;
      out.push(line);
      continue;
    }
    if (inFeatures && (line.startsWith('ORIGIN') || (line.length > 0 && line[0] !== ' '))) {
      inFeatures = false;
      skipping = false;
      out.push(line);
      continue;
    }
    if (!inFeatures) {
      out.push(line);
      continue;
    }
    const isFeatureLine = line.length > 5 && line.slice(0, 5) === '     ' && line[5] !== ' ';
    if (isFeatureLine) {
      const key = line.slice(5).trim().split(/\s+/)[0];
      if (key === 'source') {
        skipping = true;
        continue;
      }
      skipping = false;
      out.push(line);
      continue;
    }
    if (skipping) continue;
    out.push(line);
  }
  return out.join('\n');
}

function forceCircularTopology(text) {
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    if (lines[i].startsWith('LOCUS') && /\blinear\b/i.test(lines[i])) {
      lines[i] = lines[i].includes('linear  ')
        ? lines[i].replace('linear  ', 'circular')
        : lines[i].replace(/\blinear\b/i, 'circular');
      break;
    }
  }
  return lines.join('\n');
}

async function acquireEntry(entry) {
  const written = [];
  const src = entry.fetch;
  switch (src.type) {
    case 'existing':
      return [];
    case 'ncbi': {
      const url =
        `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi?db=nuccore` +
        `&id=${encodeURIComponent(src.accession)}&rettype=${src.rettype ?? 'gbwithparts'}&retmode=text` +
        `&tool=${NCBI_TOOL}&email=${encodeURIComponent(NCBI_EMAIL)}`;
      written.push({
        relPath: entry.path,
        text: assertGenBank(await httpText(url, { throttle: true }), entry.id),
      });
      break;
    }
    case 'ncbi-multi': {
      for (const item of src.accessions) {
        const accession = typeof item === 'string' ? item : item.accession;
        const name = typeof item === 'string' ? accession : item.name;
        const url =
          `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi?db=nuccore` +
          `&id=${encodeURIComponent(accession)}&rettype=${src.rettype ?? 'gbwithparts'}&retmode=text` +
          `&tool=${NCBI_TOOL}&email=${encodeURIComponent(NCBI_EMAIL)}`;
        written.push({
          relPath: `${entry.targetDir}/${name}.gb`,
          text: assertGenBank(await httpText(url, { throttle: true }), name),
        });
      }
      break;
    }
    case 'url':
      written.push({ relPath: entry.path, text: await httpText(src.url) });
      break;
    case 'github-file':
      written.push({
        relPath: entry.path,
        text: await httpText(
          `https://raw.githubusercontent.com/${src.repo}/${src.ref ?? 'HEAD'}/${src.path}`
        ),
      });
      break;
    case 'github-dir': {
      const listing = await httpJson(
        `https://api.github.com/repos/${src.repo}/contents/${encodeURIComponent(src.dir).replace(/%2F/g, '/')}?ref=${src.ref ?? 'HEAD'}`
      );
      const gbFiles = listing
        .filter((f) => f.type === 'file' && /\.(gb|gbk)$/i.test(f.name))
        .slice(0, src.limit ?? Infinity);
      for (const file of gbFiles) {
        const text = assertGenBank(await httpText(file.download_url), file.name);
        written.push({ relPath: `${entry.targetDir}/${file.name}`, text });
      }
      break;
    }
    default:
      throw new Error(`Unknown fetch type: ${src.type}`);
  }
  return written;
}

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

function disambiguateCaseCollisions(written) {
  const seen = new Map();
  for (const f of written) {
    const lower = f.relPath.toLowerCase();
    const n = (seen.get(lower) ?? 0) + 1;
    seen.set(lower, n);
    if (n > 1) {
      const dot = f.relPath.lastIndexOf('.');
      const base = dot === -1 ? f.relPath : f.relPath.slice(0, dot);
      const ext = dot === -1 ? '' : f.relPath.slice(dot);
      const renamed = `${base}-${n}${ext}`;
      console.log(`\n  case-collision (case-insensitive FS safety): ${f.relPath} → ${renamed}`);
      f.relPath = renamed;
    }
  }
  return written;
}

async function readDirGb(absDir, relDir) {
  const names = (await readdir(absDir)).filter((n) => /\.(gb|gbk)$/i.test(n)).sort();
  const out = [];
  for (const name of names) {
    out.push({ relPath: `${relDir}/${name}`, text: await readFile(join(absDir, name), 'utf8') });
  }
  return out;
}

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

async function main() {
  const manifest = JSON.parse(await readFile(MANIFEST_PATH, 'utf8'));
  const provJson = [];
  const provMd = [];
  let fetched = 0;

  for (const entry of manifest.entries) {
    if (ONLY && entry.id !== ONLY) continue;
    let files;
    if (entry.fetch.type === 'existing') {
      const abs = join(WORKSPACE_DIR, entry.path);
      files = [{ relPath: entry.path, text: await readFile(abs, 'utf8') }];
    } else {
      const isDir = Boolean(entry.targetDir);
      const target0 = join(WORKSPACE_DIR, entry.path ?? entry.targetDir);
      const need = FORCE || !(await exists(target0));
      if (!need) {
        files = isDir
          ? await readDirGb(join(WORKSPACE_DIR, entry.targetDir), entry.targetDir)
          : [
              {
                relPath: entry.path,
                text: await readFile(join(WORKSPACE_DIR, entry.path), 'utf8'),
              },
            ];
      } else {
        process.stdout.write(`fetch ${entry.id} ← ${entry.fetch.type} … `);
        files = disambiguateCaseCollisions(await acquireEntry(entry));
        for (const f of files) {
          if (/\.gbk?$/i.test(f.relPath)) {
            f.text = stripSourceFeature(f.text);
            if (/(^|\/)plasmids\//.test(f.relPath)) f.text = forceCircularTopology(f.text);
          }
          const abs = join(WORKSPACE_DIR, f.relPath);
          await mkdir(dirname(abs), { recursive: true });
          await writeFile(abs, f.text);
        }
        console.log(`ok (${files.length} file${files.length === 1 ? '' : 's'})`);
        fetched += files.length;
      }
    }

    for (const f of files) {
      const attribution =
        entry.provenance.attribution ??
        (entry.provenance.attributionTemplate ?? '').replace('{file}', basename(f.relPath));
      provJson.push({
        path: f.relPath,
        source: entry.provenance.source,
        license: entry.provenance.license,
        tier: entry.provenance.tier,
        attribution,
        ...(entry.provenance.accession ? { accession: entry.provenance.accession } : {}),
        retrieved: entry.provenance.retrieved ?? '2026-07-14',
      });
      provMd.push({
        path: `apps/desktop/resources/sample-workspaces/standard-samples/workspace/${f.relPath}`,
        source: entry.provenance.source,
        license: entry.provenance.license,
        sha256: sha256(f.text),
        generatedBy: `node apps/desktop/scripts/build-example-workspace.mjs (source id \`${entry.id}\`)`,
      });
    }
  }

  provJson.sort((a, b) => a.path.localeCompare(b.path));
  const provenanceJson = {
    $schema: 'example-workspace-provenance/v1',
    policy:
      'Every sequence shipped in this example workspace is redistribution-clean: Tier-A ' +
      '(OpenMTA / NCBI public-domain / CC0 / CC-BY) or Tier-B (a published, non-copyrightable ' +
      'DNA sequence used as fact, attributed). No sequence is downloaded from Addgene’s ' +
      'website (their ToS forbids redistributing content obtained there). Tier-B sequences are ' +
      'obtained from primary literature or third-party redistributions under their own license ' +
      '(e.g. the MIT-licensed althonos/moclo registry); the DNA sequence itself is not ' +
      'copyrightable, and we are not a party to Addgene’s ToS via those sources.',
    entries: provJson,
  };
  if (ONLY) {
    console.log(
      `\n⚠ --only ${ONLY}: provenance files NOT rewritten (a partial run would delete every other entry).\n` +
        `  The fetched file(s) above are on disk. To record them, either:\n` +
        `    • update the SHA-256 for the changed path(s) in test-fixtures/PROVENANCE.md by hand, or\n` +
        `    • re-run without --only to regenerate both provenance files in full.\n` +
        `  Verify either way with: bash tools/devops/scripts/check-fixture-provenance.sh`
    );
    console.log(`\nprovenance: skipped (partial run), fetched ${fetched} file(s)`);
    return;
  }

  await writeFile(PROVENANCE_JSON, JSON.stringify(provenanceJson, null, 2) + '\n');

  provMd.sort((a, b) => a.path.localeCompare(b.path));
  const block =
    `${MD_BEGIN}\n\n` +
    provMd
      .map(
        (e) =>
          `## ${e.path}\n\n- **Source:** ${e.source}\n- **License:** ${e.license}\n- **SHA-256:**\n  \`${e.sha256}\`\n- **Generated by:** ${e.generatedBy}\n`
      )
      .join('\n') +
    `\n${MD_END}`;
  let md = await readFile(FIXTURE_PROVENANCE_MD, 'utf8');
  if (md.includes(MD_BEGIN) && md.includes(MD_END)) {
    md = md.replace(new RegExp(`${escapeRe(MD_BEGIN)}[\\s\\S]*?${escapeRe(MD_END)}`), block);
  } else {
    md = md.trimEnd() + '\n\n' + block + '\n';
  }
  await writeFile(FIXTURE_PROVENANCE_MD, md);

  console.log(`\nprovenance: ${provJson.length} sequences (fetched ${fetched} file(s) this run)`);
  console.log(`  → ${PROVENANCE_JSON}`);
  console.log(`  → managed block in ${FIXTURE_PROVENANCE_MD}`);
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

main().catch((err) => {
  console.error('build-example-workspace failed:', err.message);
  process.exit(1);
});
