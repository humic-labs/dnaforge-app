import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SKILL_NAME = /^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/u;
const RECORD =
  /^(?<mode>[0-7]{6}) (?<type>blob) (?<sha>[a-f0-9]{40}) +(?<size>\d+)\t(?<path>[\s\S]+)$/u;
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(
  scriptDirectory,
  '../src/main/agent-capabilities/skill-catalog-seed.generated.ts'
);

function argument(name) {
  const index = process.argv.indexOf(name);
  const value = index >= 0 ? process.argv[index + 1] : null;
  if (!value || value.startsWith('--')) {
    throw new Error(`Missing ${name} repository path.`);
  }
  return resolve(value);
}

const repositories = [
  {
    packId: 'k-dense-scientific-agent-skills',
    path: argument('--k-dense'),
  },
  {
    packId: 'clawbio',
    path: argument('--clawbio'),
  },
  {
    packId: 'bioconductor-ai-agent-skills',
    path: argument('--bioconductor'),
  },
];

function git(repositoryPath, args) {
  return execFileSync('git', ['-C', repositoryPath, ...args], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }).trim();
}

function seedForRepository(repository) {
  const revision = git(repository.path, ['rev-parse', 'HEAD']);
  if (!/^[a-f0-9]{40}$/u.test(revision)) {
    throw new Error(`${repository.packId} did not resolve to a full Git revision.`);
  }
  const rawTree = execFileSync(
    'git',
    [
      '-C',
      repository.path,
      '-c',
      'core.quotePath=false',
      'ls-tree',
      '-r',
      '-l',
      '-z',
      'HEAD',
      'skills',
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
  );
  const records = rawTree.split('\0').filter(Boolean);
  const parsed = records.map((record) => {
    const match = RECORD.exec(record);
    if (!match?.groups) throw new Error(`Invalid Git tree entry in ${repository.packId}.`);
    return { record, path: match.groups.path };
  });
  const roots = new Set(
    parsed.flatMap(({ path }) => {
      const match = /^skills\/([^/]+)\/SKILL\.md$/u.exec(path);
      return match?.[1] && SKILL_NAME.test(match[1]) ? [`skills/${match[1]}`] : [];
    })
  );
  const selectedRecords = parsed
    .filter(({ path }) => [...roots].some((root) => path === root || path.startsWith(`${root}/`)))
    .map(({ record }) => record);
  if (roots.size === 0 || selectedRecords.length === 0) {
    throw new Error(`${repository.packId} contains no valid skills.`);
  }
  return {
    packId: repository.packId,
    revision,
    skillCount: roots.size,
    entries: selectedRecords.join('\0'),
  };
}

function typescriptString(value) {
  return `'${value
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\0', '\\u0000')
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t')
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029')}'`;
}

const seeds = repositories.map(seedForRepository);
const serializedSeeds = seeds
  .map(
    (seed) =>
      `  {\n    packId: ${typescriptString(seed.packId)},\n    revision: ${typescriptString(seed.revision)},\n    skillCount: ${seed.skillCount},\n    entries:\n      ${typescriptString(seed.entries)},\n  },`
  )
  .join('\n');
const source = `// Generated by scripts/generate-skill-catalog-seed.mjs. Do not edit by hand.\n\nexport interface BundledSkillCatalogSeed {\n  packId: string;\n  revision: string;\n  skillCount: number;\n  entries: string;\n}\n\nexport const BUNDLED_SKILL_CATALOG_SEEDS: readonly BundledSkillCatalogSeed[] = [\n${serializedSeeds}\n];\n`;

writeFileSync(outputPath, source, 'utf8');
for (const seed of seeds) {
  process.stdout.write(
    `${seed.packId}: ${seed.skillCount} skills at ${seed.revision.slice(0, 12)}\n`
  );
}
