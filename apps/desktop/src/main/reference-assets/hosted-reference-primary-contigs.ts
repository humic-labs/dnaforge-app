import type { HostedReferenceContigV1 } from './hosted-reference-catalog-types';

type PrimaryContigRow = readonly [
  chrom: string,
  displayName: string,
  lengthBp: number,
  refseq: string,
  genbank: string | null,
  ucsc: string | null,
  ensembl: string | null,
  organelle?: 'mitochondrion',
];

function primaryContigs(rows: readonly PrimaryContigRow[]): readonly HostedReferenceContigV1[] {
  return Object.freeze(
    rows.map(([chrom, displayName, lengthBp, refseq, genbank, ucsc, ensembl, organelle]) =>
      Object.freeze({
        chrom,
        sourceSeqId: refseq,
        displayName,
        lengthBp,
        role: organelle ?? ('assembled-molecule' as const),
        aliases: Object.freeze({
          refseq,
          ...(genbank ? { genbank } : {}),
          ...(ucsc ? { ucsc } : {}),
          ...(ensembl ? { ensembl } : {}),
        }),
        circular: organelle !== undefined,
      })
    )
  );
}

