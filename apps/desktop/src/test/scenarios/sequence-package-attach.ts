import { parseGenBankFull } from '@waypoint/sequence-utils';
import REAL_PUC19_GB from '../../../../../test-fixtures/sequences/circular/pUC19.gb?raw';
import { sidecarScenarios } from './sidecar';
import { sequencePackageFixtureDocument } from './sequence-package-fixture';
import type { AppScenario } from './types';

export const SEQUENCE_PACKAGE_ATTACH_WORKSPACE_ROOT =
  '/mock/test/workspace/sequence-package-attach';
export const SEQUENCE_PACKAGE_ATTACH_PACKAGE_ROOT = `${SEQUENCE_PACKAGE_ATTACH_WORKSPACE_ROOT}/sequences/pUC19`;
export const SEQUENCE_PACKAGE_ATTACH_PRODUCT_PATH = `${SEQUENCE_PACKAGE_ATTACH_PACKAGE_ROOT}/pUC19.gb`;
export const SEQUENCE_PACKAGE_ATTACH_META_PATH = `${SEQUENCE_PACKAGE_ATTACH_PACKAGE_ROOT}/.forge/plasmid.json`;
export const SEQUENCE_PACKAGE_ATTACH_DROP_A_PATH = `${SEQUENCE_PACKAGE_ATTACH_WORKSPACE_ROOT}/drop-inbox/clone-a/clone-1.fasta`;
export const SEQUENCE_PACKAGE_ATTACH_DROP_B_PATH = `${SEQUENCE_PACKAGE_ATTACH_WORKSPACE_ROOT}/drop-inbox/clone-b/clone-1.fasta`;
export const SEQUENCE_PACKAGE_ATTACH_GUIDE_PATH = `${SEQUENCE_PACKAGE_ATTACH_WORKSPACE_ROOT}/PROOF.md`;
export const SEQUENCE_PACKAGE_ATTACH_SESSION_NAME = ' attached clones';

const PUC19 = parseGenBankFull(REAL_PUC19_GB);
const PUC19_SEQUENCE = PUC19.sequence.toUpperCase();

export const SEQUENCE_PACKAGE_ATTACH_DROP_A_SEQUENCE = withBaseChange(PUC19_SEQUENCE, 500, 'T');
export const SEQUENCE_PACKAGE_ATTACH_DROP_B_SEQUENCE = withBaseChange(PUC19_SEQUENCE, 800, 'C');

const CREATED_AT = '2026-08-13T00:00:00.000Z';

const GUIDE = `# Sequence package attach proof

This workspace was generated by the **sequencePackageAttachTwoClones** DevPanel scenario.

The scenario runs the same attach path as dropping files on the Alignments drawer: create a session, then \`runSessionAlignments\`. That call copies the two same-name FASTAs into \`contents/\` and lists them as \`sequencing-read\` members.

## What you should see

- pUC19 is open.
- The Alignments drawer is open.
- Two clone rows: \`clone-1\` and \`clone-1-2\`.
- Each clone is full-length pUC19 with one SNP, not a 180 bp fragment.
- \`sequences/pUC19/contents/clone-1.fasta\` and \`contents/clone-1-2.fasta\` exist.
- \`.forge/plasmid.json\` is format 4 and lists both members.
- \`drop-inbox/\` still contains both original files.

Clicking this scenario again creates a new clean workspace and attaches again.
`;

function withBaseChange(sequence: string, index: number, base: string): string {
  if (index < 0 || index >= sequence.length) {
    throw new Error(`sequencePackageAttachTwoClones SNP index ${index} is out of range`);
  }
  return `${sequence.slice(0, index)}${base}${sequence.slice(index + 1)}`;
}

function fasta(name: string, sequence: string): string {
  const lines = [`>${name}`];
  for (let index = 0; index < sequence.length; index += 60) {
    lines.push(sequence.slice(index, index + 60));
  }
  return `${lines.join('\n')}\n`;
}

function attachedPackageDocument(packageId: string): string {
  return sequencePackageFixtureDocument({
    id: packageId,
    name: 'pUC19',
    productFile: 'pUC19.gb',
    updatedAt: CREATED_AT,
  });
}

export function sequencePackageAttachTwoClones(): AppScenario {
  const runId = crypto.randomUUID();
  const packageId = `dev-attach-${runId}`;
  const sequence = {
    ...PUC19,
    id: 'sequence-package-attach-puc19',
    name: 'pUC19',
  };

  return {
    dev: {
      scenarioId: `sequence-package-attach-${runId}`,
      initializeGit: true,
      initialGitCommitMessage: 'Initialize sequence package attach proof workspace',
    },
    sidecar: sidecarScenarios.fullyReady(),
    openSequenceDrawer: 'alignments',
    attachAlignmentQueries: {
      queryPaths: [SEQUENCE_PACKAGE_ATTACH_DROP_A_PATH, SEQUENCE_PACKAGE_ATTACH_DROP_B_PATH],
      sessionName: SEQUENCE_PACKAGE_ATTACH_SESSION_NAME,
      mode: 'one-per-clone',
      documentId: packageId,
      sourcePath: SEQUENCE_PACKAGE_ATTACH_PRODUCT_PATH,
    },
    workspace: {
      folders: [
        {
          path: SEQUENCE_PACKAGE_ATTACH_WORKSPACE_ROOT,
          name: 'sequence-package-attach',
        },
      ],
      selectedPath: SEQUENCE_PACKAGE_ATTACH_PRODUCT_PATH,
    },
    files: {
      [SEQUENCE_PACKAGE_ATTACH_PRODUCT_PATH]: REAL_PUC19_GB,
      [SEQUENCE_PACKAGE_ATTACH_META_PATH]: attachedPackageDocument(packageId),
      [SEQUENCE_PACKAGE_ATTACH_DROP_A_PATH]: fasta(
        'clone-1',
        SEQUENCE_PACKAGE_ATTACH_DROP_A_SEQUENCE
      ),
      [SEQUENCE_PACKAGE_ATTACH_DROP_B_PATH]: fasta(
        'clone-1-collision',
        SEQUENCE_PACKAGE_ATTACH_DROP_B_SEQUENCE
      ),
      [SEQUENCE_PACKAGE_ATTACH_GUIDE_PATH]: GUIDE,
    },
    sequences: {
      [packageId]: sequence,
    },
    canvas: {
      tabs: [
        {
          type: 'sequence',
          entityId: packageId,
          label: 'pUC19.gb',
          sequenceDocument: {
            kind: 'managed-sequence',
            packageId,
            packageRoot: SEQUENCE_PACKAGE_ATTACH_PACKAGE_ROOT,
          },
        },
      ],
      activeTabIndex: 0,
      layout: 'single',
    },
  };
}
