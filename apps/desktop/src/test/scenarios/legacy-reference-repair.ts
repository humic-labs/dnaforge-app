import { sidecarScenarios } from './sidecar';
import type { AppScenario } from './types';
import E1010M_CD from '../../../resources/sample-workspaces/standard-samples/workspace/sequences/kits/moclo-cidar/E1010m_CD/E1010m_CD.gb?raw';
import J23106_AB from '../../../resources/sample-workspaces/standard-samples/workspace/sequences/kits/moclo-cidar/J23106_AB/J23106_AB.gb?raw';
import B0015_DE from '../../../resources/sample-workspaces/standard-samples/workspace/sequences/kits/moclo-cidar/B0015_DE/B0015_DE.gb?raw';

export const LEGACY_REPAIR_ROOT = '/mock/test/workspace/legacy-reference-repair';
export const LEGACY_REPAIR_NOTEBOOK_DIR = `${LEGACY_REPAIR_ROOT}/notebooks/Red fluorescent transcription unit`;
export const LEGACY_REPAIR_GUIDE_PATH = `${LEGACY_REPAIR_ROOT}/PROOF.md`;

const PARTS = [
  { stem: 'J23106_AB', label: 'J23106 (promoter)', bytes: J23106_AB },
  { stem: 'E1010m_CD', label: 'E1010m (mRFP)', bytes: E1010M_CD },
  { stem: 'B0015_DE', label: 'B0015 (terminator)', bytes: B0015_DE },
] as const;

const KIT_DIR = 'sequences/kits/moclo-cidar';

const packagedPath = (stem: string) => `${LEGACY_REPAIR_ROOT}/${KIT_DIR}/${stem}/${stem}.gb`;
const legacyRelPath = (stem: string) => `${KIT_DIR}/${stem}.gb`;

function legacyNotebookJson(): string {
  const inline: unknown[] = [{ type: 'text', text: 'Assembled from ' }];
  PARTS.forEach((part, index) => {
    if (index > 0) inline.push({ type: 'text', text: index === PARTS.length - 1 ? ' and ' : ', ' });
    inline.push({
      type: 'mention',
      attrs: {
        id: legacyRelPath(part.stem),
        label: part.label,
        entityType: 'sequence',
        entityId: legacyRelPath(part.stem),
      },
    });
  });
  inline.push({ type: 'text', text: ' by Golden Gate.' });

  return JSON.stringify(
    {
      schema: 'waypoint.notebook.v1',
      id: 'legacy-reference-repair-notebook',
      title: 'Red fluorescent transcription unit',
      content: {
        type: 'doc',
        content: [
          {
            type: 'heading',
            attrs: { level: 1 },
            content: [{ type: 'text', text: 'Red fluorescent transcription unit' }],
          },
          { type: 'paragraph', content: inline },
          {
            type: 'paragraph',
            content: [
              {
                type: 'text',
                text: 'Every chip above was written before references carried a durable identity.',
              },
            ],
          },
        ],
      },
    },
    null,
    2
  );
}

const GUIDE = `# Legacy reference repair — proof

Generated by the **legacyReferenceRepairWorkspace** DevPanel scenario. This is a
fresh Git repository in a state that is **already broken**, reproducing exactly what
happened to a real notebook.

## What is broken, before you touch anything

The three CIDAR parts live at their **packaged** paths:

\`\`\`
${PARTS.map((p) => `${KIT_DIR}/${p.stem}/${p.stem}.gb`).join('\n')}
\`\`\`

The notebook's references point at the **old flat** paths that no longer exist:

\`\`\`
${PARTS.map((p) => legacyRelPath(p.stem)).join('\n')}
\`\`\`

Those chips carry no durable id and no content fingerprint — only a stale path. This
is the state 800 real files were left in by a packaging conversion, and it is why a
real notebook lost 12 of 12 links with no error and no warning.

## Prove the repair

1. In **Files**, open \`notebooks/Red fluorescent transcription unit\`.
   Opening it is what runs the one-time repair — nothing else is needed.
2. **Click each of the three chips.** Each must open its sequence.
   Before the fix, all three were dead.
3. Hover a chip. The card must name a path that **exists** — the packaged one,
   \`${KIT_DIR}/E1010m_CD/E1010m_CD.gb\`, not the stale flat path.
4. Open \`notebooks/Red fluorescent transcription unit/.forge/notebook.json\`
   (via **Files**). Each mention now carries a \`path\` and an \`objectUuid\`. The
   \`label\` is unchanged — the repair fixes identity, never your prose.
5. Open **Git History**. The repair is a real commit, not a hidden mutation.

## Prove it is a migration, not a healer

6. Close the notebook and open it again. **Nothing changes** — no new commit, no
   rewrite. The repair ran once. A repair that fires on every open would churn your
   file and your git history forever.

## Prove it refuses to guess

7. Note the labels (\`E1010m (mRFP)\`) do **not** match the file stems
   (\`E1010m_CD\`). The repair keys off the stored path, not the label — a
   label-keyed repair would have matched nothing here, which is exactly what it
   would have done on the real notebook.

## What success looks like

- Three chips that were dead now open their files.
- The stored references gained identity; the prose is untouched.
- A second open is a no-op.
- Selecting this scenario again builds another clean broken workspace, so a previous
  run cannot make the next one pass by accident.
`;

export function legacyReferenceRepairWorkspace(): AppScenario {
  const files: Record<string, string> = {
    [LEGACY_REPAIR_GUIDE_PATH]: GUIDE,
    [`${LEGACY_REPAIR_NOTEBOOK_DIR}/.forge/notebook.json`]: legacyNotebookJson(),
  };

  for (const part of PARTS) {
    files[packagedPath(part.stem)] = part.bytes;
  }

  return {
    dev: {
      scenarioId: `legacy-reference-repair-${crypto.randomUUID()}`,
      initializeGit: true,
      initialGitCommitMessage: 'Convert sequences to plasmid packages (references left stale)',
    },
    sidecar: sidecarScenarios.fullyReady(),
    workspace: {
      folders: [{ path: LEGACY_REPAIR_ROOT, name: 'legacy-reference-repair' }],
      selectedPath: LEGACY_REPAIR_GUIDE_PATH,
    },
    files,
    canvas: {
      tabs: [{ type: 'file', entityId: LEGACY_REPAIR_GUIDE_PATH, label: 'PROOF.md' }],
      activeTabIndex: 0,
      layout: 'single',
    },
  };
}
