def make_distribution(
    root: Path,
    name: str,
    headers: list[tuple[str, str]],
    files: dict[str, str],
    version: str = "1.0.0",
) -> metadata.PathDistribution:
    dist_info = root / f"{name.replace('-', '_')}-{version}.dist-info"
    dist_info.mkdir(parents=True)
    lines = ["Metadata-Version: 2.4", f"Name: {name}", f"Version: {version}"]
    lines += [f"{key}: {value}" for key, value in headers]
    (dist_info / "METADATA").write_text("\n".join(lines) + "\n\n")
    for relative, text in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    (dist_info / "RECORD").write_text(
        "".join(
            f"{relative},,\n" for relative in [*files, f"{dist_info.name}/METADATA"]
        )
    )
    return metadata.PathDistribution(dist_info)


def headers(*pairs: tuple[str, str]) -> Message:
    message = Message()
    for key, value in pairs:
        message[key] = value
    return message


