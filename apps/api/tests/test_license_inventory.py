def test_exported_local_sources_keep_only_the_matching_installed_package(
    tmp_path, monkeypatch
):
    api = tmp_path / "api with spaces"
    source = api / "vendor/mappy"
    source.mkdir(parents=True)

    def local_distribution(name, url):
        relative = f"{name.replace('-', '_')}-1.0.0.dist-info/direct_url.json"
        return make_distribution(
            tmp_path / name, name, [], {relative: json.dumps({"url": url})}
        )

    distributions = [
        local_distribution("mappy", source.as_uri()),
        local_distribution("unexported-dev", (api / "vendor/dev").as_uri()),
        local_distribution("remote-package", "https://example.invalid/vendor/mappy"),
        make_distribution(tmp_path / "registry", "registry-package", [], {}),
    ]
    monkeypatch.setattr(
        license_inventory.metadata, "distributions", lambda: distributions
    )
    exported = "fastapi==0.115.0\n./vendor/mappy ; sys_platform != 'win32'\n"

    def run(command, **kwargs):
        assert kwargs["cwd"] == api
        assert "--no-dev" in command
        return SimpleNamespace(stdout=exported)

    monkeypatch.setattr(license_inventory.subprocess, "run", run)
    assert license_inventory.locked_requirements([], api) == {"fastapi", "mappy"}


def test_license_label_prefers_expression_then_short_license_then_classifiers():
    assert (
        license_inventory.license_label(
            headers(("License-Expression", "MIT"), ("License", "other"))
        )
        == "MIT"
    )
    assert license_inventory.license_label(headers(("License", "Apache 2.0"))) == (
        "Apache 2.0"
    )
    assert (
        license_inventory.license_label(
            headers(
                ("License", "BSD 3-Clause License\n        Copyright notice"),
                ("Classifier", "License :: OSI Approved :: BSD License"),
                ("Classifier", "Programming Language :: Python"),
            )
        )
        == "BSD License"
    )
    assert license_inventory.license_label(headers(("License", "UNKNOWN"))) == "UNKNOWN"


def test_license_texts_come_from_the_dist_info_root_and_its_licenses_directory(
    tmp_path,
):
    distribution = make_distribution(
        tmp_path,
        "demo",
        [],
        {
            "demo-1.0.0.dist-info/LICENSE": "Root license\n",
            "demo-1.0.0.dist-info/licenses/vendor/COPYING.lib": "Vendored notice",
            "demo-1.0.0.dist-info/licenses/AUTHORS": "Root license\n",
            "demo-1.0.0.dist-info/top_level.txt": "demo",
            "demo/LICENSE": "Package copy outside the metadata",
        },
    )
    assert license_inventory.license_texts(distribution) == [
        {"file": "LICENSE", "text": "Root license"},
        {"file": "COPYING.lib", "text": "Vendored notice"},
    ]


def test_shipped_packages_follow_the_lock_add_the_compiler_and_drop_first_party(
    tmp_path,
):
    distributions = [
        make_distribution(
            tmp_path,
            "Zeta_Lib",
            [("License-Expression", "BSD-3-Clause")],
            {},
            version="2.0",
        ),
        make_distribution(tmp_path, "alpha", [("License", "MIT")], {}),
        make_distribution(tmp_path, "pytest", [("License", "MIT")], {}),
        make_distribution(tmp_path, "molbio-api", [], {}),
        make_distribution(
            tmp_path,
            "Nuitka",
            [("License", "Apache License, Version 2.0")],
            {},
            version="2.7",
        ),
    ]
    packages = license_inventory.shipped_packages(
        {"zeta-lib", "alpha", "molbio-api"}, distributions
    )
    assert [(pkg["name"], pkg["version"], pkg["license"]) for pkg in packages] == [
        ("alpha", "1.0.0", "MIT"),
        ("Nuitka", "2.7", "Apache License, Version 2.0"),
        ("Zeta_Lib", "2.0", "BSD-3-Clause"),
    ]


@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is required")
def test_inventory_of_this_environment_lists_locked_packages_with_license_texts():
    document = license_inventory.inventory([], "test-target")
    assert document["schema"] == "dnaforge.sidecar-python-licenses.v1"
    assert document["target"] == "test-target"
    assert document["python"]["implementation"] == "CPython"
    assert (
        f" {document['python']['libraries']['OpenSSL']} " in f"{ssl.OPENSSL_VERSION} "
    )
    names = [
        license_inventory.canonical_name(pkg["name"]) for pkg in document["packages"]
    ]
    assert names == sorted(names)
    assert "molbio-api" not in names
    assert "pytest" not in names
    fastapi = next(pkg for pkg in document["packages"] if pkg["name"] == "fastapi")
    assert "MIT" in fastapi["license"]
    assert any("Sebastián Ramírez" in text["text"] for text in fastapi["licenses"])
    if sys.platform != "win32":
        mappy = next(pkg for pkg in document["packages"] if pkg["name"] == "mappy")
        assert mappy["version"] == metadata.version("mappy")
        assert "MIT" in mappy["license"]
        source_license = (
            (Path(__file__).resolve().parents[1] / "vendor/mappy/LICENSE.txt")
            .read_text()
            .strip()
        )
        assert any(item["text"] == source_license for item in mappy["licenses"])
