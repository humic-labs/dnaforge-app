import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('./', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const manifest = JSON.parse(read('sources/manifest.json'));
for (const [accession, { sha256 }] of Object.entries(manifest)) {
  const content = read(`sources/${accession}.gb`);
  if (createHash('sha256').update(content).digest('hex') !== sha256)
    throw new Error(`NCBI source digest mismatch: ${accession}`);
}
const sequence = (record) =>
  record.split(/\nORIGIN\s*\n/)[1].split('//')[0].replace(/[^acgt]/gi, '').toUpperCase();
const feature = (type, location, name) =>
  `     ${type.padEnd(16)}${location}\n                     /label="${name}"\n`;
const annotate = (record, features) => record.replace(/(?=ORIGIN\s*\n)/, features.join(''));
const green = read('sources/U55762.1.gb');
const inducible = read('sources/U89931.1.gb');
const backbone = read('sources/X06402.1.gb');
const red = read('sources/AF168419.2.gb');
const puc19 = read('sources/L09137.2.gb');

const greenRecord = annotate(
  green.replace(/(     CDS\s+679\.\.1398\n)/, '$1                     /label="EGFP"\n'),
  [feature('promoter', '1..678', 'CMV promoter'), feature('polyA_signal', '1416..1638', 'SV40 polyA')]
);
const tetOperators = [...sequence(inducible).matchAll(/TCCCTATCAGTGATAGAGA/g)];
if (tetOperators.length !== 7) throw new Error('Expected seven NCBI pTRE tet operators');
const inducibleRecord = annotate(inducible, [
  feature('promoter', '1..438', 'TRE promoter'),
  ...tetOperators.map((match, index) =>
    feature('protein_bind', `${match.index + 1}..${match.index + match[0].length}`, `tetO ${index + 1}`)
  ),
]);
const backboneRecord = annotate(backbone.replace('DNA     linear', 'DNA     circular'), [
  feature('misc_feature', '766..3025', 'p15A + KanR backbone'),
]);
const redCds = sequence(red).slice(53, 731);
const redSequence = sequence(puc19) + sequence(green).slice(0, 678) + redCds + sequence(green).slice(1415, 1638);
const redRecord = [
  'LOCUS       pUC19-DsRed             4265 bp    DNA     circular SYN 12-NOV-2026',
  'DEFINITION  Synthetic pUC19 CMV-FP583 cloning and expression demo.',
  'ACCESSION   .',
  'VERSION     .',
  'KEYWORDS    synthetic; demo.',
  'SOURCE      synthetic construct',
  '  ORGANISM  synthetic construct',
  'COMMENT     Generated by ../generate.mjs from NCBI L09137.2 (1..2686),',
  '            U55762.1 (1..678), AF168419.2 (54..731), then U55762.1',
  '            (1416..1638), forward, with no base changes or added spacers.',
  '            Software demonstration; no experimental validation claimed.',
  'FEATURES             Location/Qualifiers',
  feature('source', '1..4265', 'synthetic construct').trimEnd(),
  feature('misc_feature', '1..2686', 'pUC19 backbone (L09137.2)').trimEnd(),
  feature('promoter', '2687..3364', 'CMV promoter').trimEnd(),
  feature('CDS', '3365..4042', 'DsRed (FP583)').trimEnd(),
  feature('polyA_signal', '4043..4265', 'SV40 polyA (red vector)').trimEnd(),
  'ORIGIN',
  ...Array.from({ length: Math.ceil(redSequence.length / 60) }, (_, i) =>
    `${String(i * 60 + 1).padStart(9)} ${redSequence.slice(i * 60, i * 60 + 60).toLowerCase().match(/.{1,10}/g).join(' ')}`
  ),
  '//',
  '',
].join('\n');

for (const [name, record] of Object.entries({
  'pEGFP-N1.gb': greenRecord,
  'pTRE.gb': inducibleRecord,
  'pACYC177.gb': backboneRecord,
  'pUC19-DsRed.gb': redRecord,
})) {
  writeFileSync(new URL(`plasmids/${name}`, root), record);
  console.log(`${name} ${sequence(record).length} bp ${createHash('sha256').update(record).digest('hex')}`);
}
